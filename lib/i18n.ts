export function formatMoney(amount: number, locale: Locale, currency: Currency = "KZT") {
  const whole = String(Math.floor(Math.abs(amount) / 100)).replace(/\B(?=(\d{3})+(?!\d))/g, locale === "en" ? "," : "\u00a0");
  const fraction = Math.abs(amount) % 100;
  return `${amount < 0 ? "−" : ""}${whole}${fraction ? (locale === "en" ? "." : ",") + String(fraction).padStart(2, "0") : ""} ${currency === "KZT" ? "₸" : currency}`;
}
