export function formatDate(value: string, locale: Locale, full = false) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return "—";
  const parsed = new Date(`${value}T12:00:00Z`);
  if (!Number.isFinite(parsed.getTime()) || parsed.toISOString().slice(0,10) !== value) return "—";
  const [year, month, day] = value.split("-").map(Number);
  if (full) return locale === "en" ? `${fullMonths.en[month - 1]} ${day}, ${year}` : `${day} ${fullMonths[locale][month - 1]} ${year}`;
  return locale === "en" ? `${shortMonths.en[month - 1]} ${day}` : `${day} ${shortMonths[locale][month - 1].toLowerCase()}.`;
}
